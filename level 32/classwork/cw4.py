# 4) შექმენი Set სახელად `numbers`, რომელშიც იქნება 6 განსხვავებული რიცხვი.
# `remove()` მეთოდით წაშალე ერთი რიცხვი, `add()` მეთოდით დაამატე ახალი რიცხვი და `in` ოპერატორით შეამოწმე, არის თუ არა ახალი რიცხვი Set-ში.

numbers = {12, 2, 5, 65, 6, 2}

numbers.remove(12)
numbers.add(23)
print(23 in numbers)