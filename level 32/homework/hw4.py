# 4) შექმენი Set სახელად `scores`, რომელშიც იქნება 6 განსხვავებული რიცხვი.
# `discard()` მეთოდით წაშალე ერთ-ერთი რიცხვი, `add()` მეთოდით დაამატე ახალი რიცხვი და `in` ოპერატორით შეამოწმე, არის თუ არა ეს რიცხვი Set-ში.

scores = {11, 15, 3, 5, 1, 78}
scores.discard(11)
scores.add(144)
print(144 in scores)