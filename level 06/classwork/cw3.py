#3) შექმენი ორი ცვლადი, რომლებშიც შეინახავ ორ სხვადასხვა ტემპერატურას. შეადარე ისინი ოპერატორების (`>`, `<`, `>=`, `<=`, `!=`, `==`) გამოყენებით.

temp1 = int(input("enter first temperature: "))
temp2 = int(input("enter second temperature: "))
print(temp1 > temp2)
print(temp1 < temp2)
print(temp1 >= temp2)
print(temp1 <= temp2)
print(temp1 != temp2)
print(temp1 == temp2)